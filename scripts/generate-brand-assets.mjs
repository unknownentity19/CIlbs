import sharp from "sharp";
import { mkdirSync } from "node:fs";

/**
 * Renders every brand asset from one master file, so the favicon, the app
 * icon, the OG card, and the in-app logo can't drift apart.
 *
 *   node scripts/generate-brand-assets.mjs
 *
 * The master (brand/logo-master.webp) is the artwork as supplied: 1254px with
 * a real alpha channel. It is trimmed to its content here rather than in the
 * source file, so the original stays untouched and re-croppable.
 */

const MASTER = "brand/logo-master.webp";

/** Trim the transparent margin, then re-pad to a square with a small breathing
 * gap — the artwork's own padding is uneven (49px left, 33px right), which
 * would make the mark sit visibly off-centre in a square favicon. */
async function squared(size, { padding = 0.06 } = {}) {
  const inner = Math.round(size * (1 - padding * 2));
  const trimmed = await sharp(MASTER)
    .trim({ threshold: 1 })
    .resize(inner, inner, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer();

  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: trimmed, gravity: "center" }])
    .png({ compressionLevel: 9 });
}

mkdirSync("public", { recursive: true });

const transparent = [
  { file: "public/logo.png", size: 1024 },
  { file: "public/logo-512.png", size: 512 },
  // Favicon. A raster one replaces the old SVG: this artwork uses gradients
  // and translucent overlaps, which don't survive being traced to paths.
  { file: "src/app/icon.png", size: 256 },
];

for (const { file, size } of transparent) {
  await (await squared(size)).toFile(file);
  console.log(`wrote ${file} (${size}px, transparent)`);
}

// iOS composites the home-screen icon onto the wallpaper and masks its own
// corners, so a transparent one shows through as black. White matches the
// artwork's own negative space.
const apple = await squared(180, { padding: 0.1 });
await sharp(await apple.toBuffer())
  .flatten({ background: "#ffffff" })
  .png({ compressionLevel: 9 })
  .toFile("src/app/apple-icon.png");
console.log("wrote src/app/apple-icon.png (180px, white plate for iOS)");

// The OG card renders through Satori, which needs the bytes inline.
const og = await (await squared(256)).toBuffer();
const { writeFileSync } = await import("node:fs");
writeFileSync(
  "src/components/brand/mark-data.ts",
  `// Generated by scripts/generate-brand-assets.mjs — do not edit by hand.\n` +
    `// The logomark as a data URI, for surfaces that can't fetch a file:\n` +
    `// the Open Graph card is rendered by Satori at build time.\n` +
    `export const MARK_DATA_URI =\n  "data:image/png;base64,${og.toString("base64")}";\n`,
);
console.log("wrote src/components/brand/mark-data.ts");
